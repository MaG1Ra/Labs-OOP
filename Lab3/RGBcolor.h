/**
 * @file RGBColor.h
 * @brief Объявление класса RGBColor, представляющего цвет в модели RGB.
 */
#ifndef OOP_RGBCOLOR_H
#define OOP_RGBCOLOR_H
/**
 * @class RGBColor
 * @brief Цвет в модели RGB: красная, зелёная и синяя составляющие в диапазоне 0–255.
 *
 * @details Класс демонстрирует перегрузку операторов:
 * - унарные `++` и `--` в префиксной и постфиксной форме (увеличение и уменьшение яркости);
 * - арифметическое присваивание `+=`, `-=`, `*=`, `/=`;
 * - бинарные `+`, `-`, `*`, `/`, которые реализованы через `+=`, `-=`, `*=`, `/=`;
 * - сравнение по яркости `<`, `>`, `<=`, `>=`, `==`, `!=`.
 *
 * Дополнительно в классе используются:
 * - статическое поле RGBColor::counter, по которому определяется количество цветов в палитре;
 * - деструктор, уменьшающий этот счётчик.
 *
 * @note Результаты всех операций ограничиваются диапазоном 0–255,
 *       переполнения не происходит.
 */
class RGBColor {
    unsigned char red = 0;     ///< Красная составляющая цвета (0–255).
    unsigned char green = 0;   ///< Зелёная составляющая цвета (0–255).
    unsigned char blue = 0;    ///< Синяя составляющая цвета (0–255).
    static int counter;        ///< Количество существующих объектов RGBColor, то есть цветов в палитре (общее для всего класса).
    /**
     * @brief Ограничивает значение диапазоном 0–255.
     * @param value Исходное значение (может выходить за пределы диапазона).
     * @return 0, если value меньше 0; 255, если value больше 255; иначе value.
     */
    unsigned char clamp(int value);
    /**
     * @brief Вычисляет яркость цвета.
     * @details Яркость считается как сумма каналов:
     *          `0.2126 * R + 0.7152 * G + 0.0722 * B`.
     *          По этому значению сравниваются цвета.
     * @return Яркость цвета (чем больше значение, тем цвет светлее).
     */
    double luminance() const;
    mutable int req_counter = 0;   ///< Счётчик обращений к объекту. Объявлен как `mutable`, поэтому меняется и у `const`-объекта.
public:
    /**
     * @brief Конструктор по умолчанию.
     * @details Создаёт чёрный цвет (0, 0, 0) и увеличивает счётчик цветов в палитре.
     */
    RGBColor();
    /**
     * @brief Конструктор с параметрами.
     * @param red_   Красная составляющая (0–255).
     * @param green_ Зелёная составляющая (0–255).
     * @param blue_  Синяя составляющая (0–255).
     * @note Конструктор объявлен как `explicit`: объект нужно создавать явно,
     *       `RGBColor c(10, 20, 30);`. Неявная форма `RGBColor c = {10, 20, 30};`
     *       не компилируется.
     */
    explicit RGBColor(unsigned char red_, unsigned char green_, unsigned char blue_);
    /**
     * @brief Конструктор копирования.
     * @details Копирует три канала цвета и увеличивает счётчик цветов в палитре.
     *          Счётчик обращений RGBColor::req_counter у нового объекта начинается с нуля.
     * @param other Копируемый цвет.
     */
    RGBColor(const RGBColor& other);
    /**
     * @brief Деструктор.
     * @details Уменьшает счётчик цветов в палитре RGBColor::counter.
     */
    ~RGBColor();
    /**
     * @brief Префиксный инкремент: увеличивает яркость цвета.
     * @details Каждый канал увеличивается на 1, значение не превышает 255.
     *          Увеличивает счётчик обращений.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator++();
    /**
     * @brief Постфиксный инкремент: увеличивает яркость цвета.
     * @details Каждый канал увеличивается на 1, значение не превышает 255.
     *          Безымянный параметр типа `int` нужен только для того, чтобы отличить
     *          постфиксную форму от префиксной.
     * @return Копия цвета до изменения.
     */
    RGBColor operator++(int);
    /**
     * @brief Префиксный декремент: уменьшает яркость цвета.
     * @details Каждый канал уменьшается на 1, значение не опускается ниже 0.
     *          Увеличивает счётчик обращений.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator--();
    /**
     * @brief Постфиксный декремент: уменьшает яркость цвета.
     * @details Каждый канал уменьшается на 1, значение не опускается ниже 0.
     *          Безымянный параметр типа `int` отличает постфиксную форму от префиксной.
     * @return Копия цвета до изменения.
     */
    RGBColor operator--(int);
    /**
     * @brief Сложение цветов с присваиванием (осветление).
     * @details К каждому каналу прибавляется соответствующий канал rhs, результат не превышает 255.
     * @param rhs Прибавляемый цвет.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator+=(const RGBColor& rhs);
    /**
     * @brief Вычитание цветов с присваиванием (затемнение).
     * @details Из каждого канала вычитается соответствующий канал rhs, результат не меньше 0.
     * @param rhs Вычитаемый цвет.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator-=(const RGBColor& rhs);
    /**
     * @brief Умножение цветов с присваиванием (смешивание).
     * @details Каждый канал вычисляется как `канал * rhs.канал / 255`.
     *          Деление на 255 нужно, чтобы результат оставался в шкале 0–255:
     *          белый цвет (255) не меняет второй цвет, чёрный (0) даёт чёрный.
     * @param rhs Цвет, на который умножаем.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator*=(const RGBColor& rhs);
    /**
     * @brief Деление цветов с присваиванием (операция, обратная умножению).
     * @details Каждый канал вычисляется как `канал * 255 / rhs.канал`, результат не превышает 255.
     * @note Если канал делителя rhs равен 0, результат для этого канала равен 255,
     *       то есть деления на ноль не происходит.
     * @param rhs Цвет-делитель.
     * @return Ссылка на изменённый объект.
     */
    RGBColor& operator/=(const RGBColor& rhs);

    /**
     * @brief Сумма двух цветов.
     * @details Левый операнд передаётся по значению, то есть это его копия.
     *          К копии применяется RGBColor::operator+=, поэтому исходные объекты не меняются.
     * @param lhs Левый операнд (копия).
     * @param rhs Правый операнд.
     * @return Новый цвет: результат сложения.
     */
    friend RGBColor operator+(RGBColor lhs, const RGBColor& rhs);
    /**
     * @brief Разность двух цветов.
     * @details Реализована через RGBColor::operator-= на копии левого операнда.
     * @param lhs Левый операнд (копия).
     * @param rhs Правый операнд.
     * @return Новый цвет: результат вычитания.
     */
    friend RGBColor operator-(RGBColor lhs, const RGBColor& rhs);
    /**
     * @brief Произведение двух цветов (смешивание).
     * @details Реализовано через RGBColor::operator*= на копии левого операнда.
     * @param lhs Левый операнд (копия).
     * @param rhs Правый операнд.
     * @return Новый цвет: результат умножения.
     */
    friend RGBColor operator*(RGBColor lhs, const RGBColor& rhs);
    /**
     * @brief Частное двух цветов.
     * @details Реализовано через RGBColor::operator/= на копии левого операнда.
     * @param lhs Левый операнд (копия).
     * @param rhs Правый операнд.
     * @return Новый цвет: результат деления.
     */
    friend RGBColor operator/(RGBColor lhs, const RGBColor& rhs);

    /**
     * @brief Сравнение яркости: яркость этого цвета меньше яркости rhs.
     * @details Метод константный, но увеличивает `mutable`-счётчик обращений RGBColor::req_counter.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если этот цвет темнее rhs.
     */
    bool operator<(const RGBColor& rhs) const;
    /**
     * @brief Сравнение яркости: яркость этого цвета больше яркости rhs.
     * @details Увеличивает счётчик обращений RGBColor::req_counter, в том числе у `const`-объекта.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если этот цвет светлее rhs.
     */
    bool operator>(const RGBColor& rhs) const;
    /**
     * @brief Сравнение яркости: яркость этого цвета меньше яркости rhs или равна ей.
     * @details Увеличивает счётчик обращений RGBColor::req_counter.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если этот цвет не светлее rhs.
     */
    bool operator<=(const RGBColor& rhs) const;
    /**
     * @brief Сравнение яркости: яркость этого цвета больше яркости rhs или равна ей.
     * @details Увеличивает счётчик обращений RGBColor::req_counter.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если этот цвет не темнее rhs.
     */
    bool operator>=(const RGBColor& rhs) const;
    /**
     * @brief Проверка на равенство по яркости.
     * @details Цвета считаются равными, если их яркости совпадают (это не обязательно один и тот же цвет).
     *          Увеличивает счётчик обращений RGBColor::req_counter.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если яркости цветов равны.
     */
    bool operator==(const RGBColor& rhs) const;
    /**
     * @brief Проверка на неравенство по яркости.
     * @details Увеличивает счётчик обращений RGBColor::req_counter.
     * @param rhs Сравниваемый цвет.
     * @return `true`, если яркости цветов различаются.
     */
    bool operator!=(const RGBColor& rhs) const;

    /**
     * @brief Возвращает красную составляющую цвета.
     * @return Значение канала от 0 до 255.
     */
    unsigned char getRGBColorRed() const;
    /**
     * @brief Возвращает зелёную составляющую цвета.
     * @return Значение канала от 0 до 255.
     */
    unsigned char getRGBColorGreen() const;
    /**
     * @brief Возвращает синюю составляющую цвета.
     * @return Значение канала от 0 до 255.
     */
    unsigned char getRGBColorBlue() const;
    /**
     * @brief Выводит цвет в стандартный поток вывода.
     * @details Формат вывода: `RGB (красный, зелёный, синий)` и перевод строки.
     */
    void print() const;
    /**
     * @brief Возвращает количество цветов в палитре.
     * @details Статический метод: вызывается без объекта, `RGBColor::getCounter()`.
     *          Учитываются все существующие объекты, в том числе временные.
     * @return Количество существующих объектов RGBColor.
     */
    static int getCounter();
    /**
     * @brief Возвращает счётчик обращений к объекту.
     * @details Метод константный, поэтому его можно вызвать у `const`-объекта.
     * @return Сколько раз выполнялись операции, увеличивающие RGBColor::req_counter.
     */
    int getReqCounter() const;
};
#endif //OOP_RGBCOLOR_H
